//! Emit the same trace as textual LLVM IR, plus a C driver to run it.
//!
//! TPDE is a C++ library and cannot be called from this binary, so the
//! comparison goes through files: this writes `trace.ll`, the measurement
//! script hands it to `tpde-llc` and to `llc`, and both objects get linked
//! against the same driver. The IR is the same program the Cranelift builder
//! produces, block for block and operation for operation, so the two back ends
//! are being asked the same question.
//!
//! It is unoptimized SSA with explicit phi nodes and no `alloca`, which is what
//! a JIT front end hands a back end. Running mem2reg first and then declaring a
//! back end fast would be measuring the wrong pass.

use std::fmt::Write as _;

use crate::trace::{Trace, heap};

fn acc_before(k: usize) -> String {
    if k == 0 {
        "%acc".to_string()
    } else {
        format!("%acc.{}", k - 1)
    }
}

pub fn emit_ir(trace: &Trace) -> String {
    assert!(!trace.ops.is_empty(), "an empty trace has nothing to compile");
    let last = trace.ops.len() - 1;
    let mut s = String::with_capacity(trace.ops.len() * 400);

    s.push_str("; Generated by m03. See experiments/m0.3-jit-backend/README.md.\n");
    s.push_str("declare i64 @deopt(i64, i64, double)\n\n");
    s.push_str("define i64 @trace(ptr %slots, ptr %out, i64 %iters) {\n");
    s.push_str("entry:\n  br label %head\n\n");

    let _ = write!(
        s,
        "head:\n  \
         %i = phi i64 [ 0, %entry ], [ %i.next, %latch ]\n  \
         %acc = phi double [ 0.0, %entry ], [ %acc.{last}, %latch ]\n  \
         %more = icmp slt i64 %i, %iters\n  \
         br i1 %more, label %guard.0, label %done\n\n"
    );

    for (k, g) in trace.ops.iter().enumerate() {
        let prev = acc_before(k);
        let next = if k == last {
            "latch".to_string()
        } else {
            format!("guard.{}", k + 1)
        };

        let _ = write!(
            s,
            "guard.{k}:\n  \
             %slot.{k} = getelementptr inbounds i8, ptr %slots, i64 {slot}\n  \
             %base.{k} = load ptr, ptr %slot.{k}, align 8\n  \
             %shape.{k} = load i64, ptr %base.{k}, align 8\n  \
             %ok.{k} = icmp eq i64 %shape.{k}, {shape}\n  \
             br i1 %ok.{k}, label %body.{k}, label %cold.{k}\n\n",
            slot = k * 8,
            shape = g.shape_id,
        );

        let _ = write!(
            s,
            "body.{k}:\n  \
             %xp.{k} = getelementptr inbounds i8, ptr %base.{k}, i64 8\n  \
             %x.{k} = load double, ptr %xp.{k}, align 8\n  \
             %yp.{k} = getelementptr inbounds i8, ptr %base.{k}, i64 16\n  \
             %y.{k} = load double, ptr %yp.{k}, align 8\n  \
             %t.{k} = {opcode} double %x.{k}, %y.{k}\n  \
             %acc.{k} = fadd double {prev}, %t.{k}\n  \
             store double %y.{k}, ptr %xp.{k}, align 8\n  \
             store double %x.{k}, ptr %yp.{k}, align 8\n  \
             br label %{next}\n\n",
            opcode = g.op.llvm(),
        );

        let _ = write!(
            s,
            "cold.{k}:\n  \
             %d.{k} = call i64 @deopt(i64 {k}, i64 %i, double {prev})\n  \
             store double {prev}, ptr %out, align 8\n  \
             ret i64 %d.{k}\n\n"
        );
    }

    s.push_str("latch:\n  %i.next = add i64 %i, 1\n  br label %head\n\n");
    s.push_str("done:\n  store double %acc, ptr %out, align 8\n  ret i64 0\n}\n");
    s
}

/// The C driver, generated rather than checked in so that the heap it sets up
/// cannot drift from the heap `trace::heap` builds for the Cranelift run.
pub fn emit_driver(trace: &Trace, iters: i64) -> String {
    let words = heap(trace.objects);
    let expected = crate::trace::evaluate(trace, iters);

    let mut s = String::new();
    s.push_str(
        "/* Generated by m03. Times the compiled trace and checks its answer.\n\
         \x20  The heap literal below is the same one the Cranelift run uses, emitted\n\
         \x20  from the same source, because two nearly identical heaps would make the\n\
         \x20  two back ends look different for a reason that is not the back end. */\n\
         #include <stdint.h>\n\
         #include <stdio.h>\n\
         #include <string.h>\n\
         #include <time.h>\n\n\
         int64_t trace(void **slots, double *out, int64_t iters);\n\n\
         int64_t deopt(int64_t id, int64_t iter, double acc) {\n\
         \x20 (void)iter; (void)acc;\n\
         \x20 return id + 1;\n\
         }\n\n",
    );

    let _ = writeln!(s, "static const int64_t seed[{}] = {{", words.len());
    for chunk in words.chunks(4) {
        let line: Vec<String> = chunk.iter().map(|w| format!("{w}LL")).collect();
        let _ = writeln!(s, "  {},", line.join(", "));
    }
    s.push_str("};\n\n");

    let offsets = crate::trace::offsets(trace);
    let _ = writeln!(s, "static const int64_t offsets[{}] = {{", offsets.len());
    for chunk in offsets.chunks(16) {
        let line: Vec<String> = chunk.iter().map(|o| o.to_string()).collect();
        let _ = writeln!(s, "  {},", line.join(", "));
    }
    s.push_str("};\n\n");

    let _ = write!(
        s,
        "int main(void) {{\n\
         \x20 int64_t objects[{n}];\n\
         \x20 memcpy(objects, seed, sizeof objects);\n\
         \x20 /* One pointer per operation, the way a Python list holds\n\
         \x20    references. See trace::evaluate for why this matters. */\n\
         \x20 static void *slots[{ops}];\n\
         \x20 for (int k = 0; k < {ops}; k++)\n\
         \x20   slots[k] = (char *)objects + offsets[k];\n\
         \x20 double out = 0.0;\n\
         \x20 struct timespec a, b;\n\
         \x20 clock_gettime(CLOCK_MONOTONIC, &a);\n\
         \x20 int64_t ret = trace(slots, &out, {iters}LL);\n\
         \x20 clock_gettime(CLOCK_MONOTONIC, &b);\n\
         \x20 double ns = (double)(b.tv_sec - a.tv_sec) * 1e9 + (double)(b.tv_nsec - a.tv_nsec);\n\
         \x20 uint64_t got, want;\n\
         \x20 memcpy(&got, &out, 8);\n\
         \x20 uint64_t w = {bits}ULL;\n\
         \x20 memcpy(&want, &w, 8);\n\
         \x20 printf(\"{{\\\"run_ns\\\": %.0f, \\\"ret\\\": %lld, \\\"out_bits\\\": %llu, \\\"ok\\\": %d}}\\n\",\n\
         \x20        ns, (long long)ret, (unsigned long long)got, got == want);\n\
         \x20 return got == want ? 0 : 1;\n\
         }}\n",
        n = words.len(),
        ops = trace.ops.len(),
        bits = expected.to_bits(),
    );
    s
}
